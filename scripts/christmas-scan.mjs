// Scan each pub's own website (cached by scripts/enrich.mjs in data/raw/sites/) for Christmas and New Year's Eve
// mentions, and write data/christmas-web.json. These flags let a pub appear on a Christmas page with basis "website".
// Nothing else (menus, prices, dates, capacities, hours) is taken from the text: those come only from the
// hand-checked data/christmas.json.
//
// Usage: node scripts/christmas-scan.mjs
import fs from 'node:fs/promises';
import path from 'node:path';

const SITE_DIR = 'data/raw/sites';
const OUT = 'data/christmas-web.json';

// Each flag: patterns that must match, and context (±120 chars) that disqualifies a match.
const RULES = {
  festiveMenu: {
    match: /\b(christmas|xmas|festive) (day )?(menus?|lunch(es)?|dinners?|feast|food)\b|\bchristmas (lunch|dinner) or dinner\b/i,
    // Cocktail-class "festive menu", chain-wide FAQs, and offer small print are not this pub's Christmas food.
    reject: /cocktail|masterclass|one of our pubs|depend on the venue|cannot be used|bank holidays/i,
  },
  christmasDay: {
    match: /\b(christmas|xmas) day (menus?|lunch|dinner)\b|\bdinner on christmas day\b|\bchristmas day done properly\b|\b(take care of everything|joining us|join us) on christmas day\b/i,
    reject: /excluding|except|not be open for food|cannot be used|bank holidays|deposit/i,
  },
  christmasParty: {
    match: /\b(christmas|xmas|festive|office) part(y|ies)\b/i,
    reject: /one of our pubs|depend on the venue|reviewer|trip ?advisor|countryside/i,
  },
  groupBookings: {
    match: /\b(function room|private hire|private room|group bookings?|exclusive hire|private (event|function) (room|space)s?)\b/i,
    // Booking terms and conditions and quoted reviews are not an offer of group bookings.
    reject: /one of our pubs|depend on the venue|means a booking|clause|reviewer|trip ?advisor/i,
  },
  newYearsEve: {
    // Must read as this pub's own event or menu, not a list of occasions or an offer exclusion.
    match: /\bnew year'?s? eve (menu|party|parties|event|celebration|at|night|tickets?)\b|\bnew year'?s? eve\b(?=[\s\S]{0,90}\b(bring everyone|join us|celebrate|countdown)\b)/i,
    reject: /cannot be used|excludes?|excluding|except|bank holidays/i,
  },
};

// Manual corrections after reading the matches (slug -> flags to drop), with the reason.
const DROP = {
  // Be At One's "festive menu" is its cocktail and drinks-package list, not food.
  'be-at-one-brighton': ['festiveMenu'],
  // "NEW YEAR'S EVE" here is a link in a sister venue's menu bar, not an event at this pub.
  'blind-busker': ['newYearsEve'],
  // Fuller's site boilerplate mentions a "countryside location"; its function room is real, the party copy is generic.
  'the-grand-central-brighton': ['christmasParty'],
  // Greene King chain copy ("Christmas dinner, party-perfect buffets") with no Station-specific menu.
  'the-station': ['festiveMenu', 'christmasParty'],
};

const clean = (s) => s.replace(/\s+/g, ' ').trim();

async function main() {
  const out = {};
  for (const file of (await fs.readdir(SITE_DIR)).sort()) {
    const slug = file.replace(/\.json$/, '');
    const site = JSON.parse(await fs.readFile(path.join(SITE_DIR, file), 'utf8'));
    const flags = {};
    for (const [key, rule] of Object.entries(RULES)) {
      if ((DROP[slug] || []).includes(key)) continue;
      for (const page of site.pages || []) {
        // Booking terms and privacy pages describe contracts, not what the pub offers.
        if (/terms|conditions|privacy|cookie/i.test(page.url)) continue;
        const re = new RegExp(rule.match.source, 'gi');
        let m;
        while ((m = re.exec(page.text || ''))) {
          const ctx = page.text.slice(Math.max(0, m.index - 120), m.index + m[0].length + 120);
          if (rule.reject.test(ctx)) continue;
          flags[key] = { url: page.url, quote: clean(page.text.slice(Math.max(0, m.index - 60), m.index + m[0].length + 60)) };
          break;
        }
        if (flags[key]) break;
      }
    }
    if (Object.keys(flags).some((k) => k !== 'groupBookings') || flags.groupBookings)
      out[slug] = { checked: (site.fetchedAt || '').slice(0, 10), ...flags };
  }
  const ordered = Object.fromEntries(Object.entries(out).sort(([a], [b]) => a.localeCompare(b)));
  await fs.writeFile(OUT, JSON.stringify({ _comment: 'Generated by scripts/christmas-scan.mjs from each pub\'s own website. Flags only; quotes are kept for checking and are never shown on the site.', ...ordered }, null, 2) + '\n');
  const count = (k) => Object.values(out).filter((v) => v[k]).length;
  console.log(Object.keys(RULES).map((k) => `${k}: ${count(k)}`).join(', '));
}
main();
